"""中国节假日 / 节日名查询。

滴答清单的日历在日期号旁显示「休 / 班」角标，并在格子里标出节日名，
所以这块必须独立成一个纯数据模块，而不是散在视图里。

数据来源：
- 「休 / 班」用国务院办公厅发布的年度放假安排（2026 年已核实原文），
  没有数据的年份退化为「周末即休」，不猜调休，避免标错；
- 农历节日（春节 / 元宵 / 端午 / 七夕 / 中秋 / 重阳 / 腊八 / 小年）
  依赖农历换算，与其塞一张记不准的农历表静默算错日期，
  不如按年存已核实的公历日期，缺哪年就少标哪年。
"""
from __future__ import annotations

from PySide6.QtCore import QDate

# 公历固定日期节日
SOLAR = {
    (1, 1): "元旦",
    (2, 14): "情人节",
    (3, 8): "妇女节",
    (3, 12): "植树节",
    (4, 1): "愚人节",
    (5, 1): "劳动节",
    (5, 4): "青年节",
    (6, 1): "儿童节",
    (7, 1): "建党节",
    (8, 1): "建军节",
    (9, 10): "教师节",
    (10, 1): "国庆节",
    (11, 8): "记者节",
    (12, 24): "平安夜",
    (12, 25): "圣诞节",
}

# 农历节日 → 该年对应的公历日期（已核实）
LUNAR = {
    2026: {
        "01-26": "腊八节", "02-10": "小年", "02-16": "除夕", "02-17": "春节",
        "03-03": "元宵节", "04-05": "清明节", "06-19": "端午节", "08-19": "七夕节",
        "08-27": "中元节", "09-25": "中秋节", "10-18": "重阳节",
    },
}

# 第 N 个星期几类节日：(月, 第几个, weekday 0=周一) → 名称
NTH_WEEKDAY = {
    (5, 2, 6): "母亲节",
    (6, 3, 6): "父亲节",
}

# 国务院办公厅放假安排：off=放假，work=调休上班
STATUTORY = {
    2026: {
        "off": {"01-01", "01-02", "01-03",
                "02-15", "02-16", "02-17", "02-18", "02-19", "02-20",
                "02-21", "02-22", "02-23",
                "04-04", "04-05", "04-06",
                "05-01", "05-02", "05-03", "05-04", "05-05",
                "06-19", "06-20", "06-21",
                "09-25", "09-26", "09-27",
                "10-01", "10-02", "10-03", "10-04", "10-05", "10-06", "10-07"},
        "work": {"01-04", "02-14", "02-28", "05-09", "09-20", "10-10"},
    },
}

# 法定节假日名（用于「重要节日」判断，颜色与普通节日区分）
MAJOR = {"元旦", "春节", "除夕", "清明节", "劳动节", "端午节", "中秋节", "国庆节"}


def _key(d: QDate) -> str:
    return f"{d.month():02d}-{d.day():02d}"


def festival(d: QDate) -> str:
    """当天节日名，无则空串。农历节日优先于公历固定节日。"""
    name = LUNAR.get(d.year(), {}).get(_key(d))
    if name:
        return name
    name = SOLAR.get((d.month(), d.day()))
    if name:
        return name
    # Qt 的 dayOfWeek 周一=1…周日=7，这里按 Python weekday（周一=0）计数
    nth = (d.day() - 1) // 7 + 1
    return NTH_WEEKDAY.get((d.month(), nth, d.dayOfWeek() - 1), "")


def is_major(d: QDate) -> bool:
    return festival(d) in MAJOR


def day_type(d: QDate) -> str:
    """'休' / '班' / ''。有官方安排按官方，否则周末算休。"""
    weekend = d.dayOfWeek() >= 6
    rule = STATUTORY.get(d.year())
    if not rule:
        return "休" if weekend else ""
    if _key(d) in rule["work"]:
        return "班"
    if _key(d) in rule["off"]:
        return "休"
    return "休" if weekend else ""
